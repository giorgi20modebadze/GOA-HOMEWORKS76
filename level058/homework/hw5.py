#შექმენით ყველანაირი მონაცემთა ტიპების ელემენტებით სავსე სია, ამოშალეთ ყველა დუპლიკატები - ყველაფერი რაც მეორდება 2-ზე მეტჯერ, გამოიყენეთ remove() ფუნქცია და while ციკლი.

list1 = [1, 2, 2, 1, "გიორგი", "თბილისი",  4.5, 8, "true", "false", "false"]

i = 0


while i < len(list1):
    if list1.count(list1[i]) > 2:
        list1.remove(list1[i])
        
    else:
        i += 1



print(list1)
